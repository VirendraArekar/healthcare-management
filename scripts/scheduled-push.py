#!/usr/bin/env python3
"""Apply reviewed patches in isolated worktrees and push at 15-minute intervals."""
import argparse
import datetime
import fcntl
import json
from pathlib import Path
import subprocess
import tempfile
import time


def run(args, cwd, timeout=600):
    return subprocess.run(args, cwd=cwd, check=True, text=True,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          timeout=timeout).stdout.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('queue', type=Path)
    parser.add_argument('--remote', default='origin')
    parser.add_argument('--branch', default='main')
    args = parser.parse_args()
    root = Path(run(['git', 'rev-parse', '--show-toplevel'], Path.cwd()))
    queue_path = args.queue.resolve()
    changes = json.loads(queue_path.read_text())
    if not isinstance(changes, list) or not changes:
        parser.error('Queue must contain at least one reviewed change; see docs/scheduled-push.md')
    for change in changes:
        if not change.get('message', '').strip() or not change.get('checks'):
            parser.error('Each change requires a message and checks')
        if not all(isinstance(c, list) and c and all(isinstance(v, str) for v in c)
                   for c in change['checks']):
            parser.error('Checks must be nonempty arrays of command arguments')
        change['patch'] = str((queue_path.parent / change['patch']).resolve(strict=True))
    base = run(['git', 'rev-parse', 'HEAD'], root)
    run(['git', 'check-ref-format', 'refs/heads/' + args.branch], root)
    run(['git', 'remote', 'get-url', args.remote], root)
    directory = root / '.scheduled-push'
    directory.mkdir(exist_ok=True)
    lock = (directory / 'lock').open('w')
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    state_path = directory / 'state.json'
    identity = {'queue': changes, 'remote': args.remote, 'branch': args.branch}
    state = json.loads(state_path.read_text()) if state_path.exists() else {
        'identity': identity, 'index': 0, 'pushes': 0, 'failed': 0,
        'base': base, 'pending': None}
    if state['identity'] != identity:
        parser.error('Queue or destination differs from saved state; archive .scheduled-push first')

    def save():
        temporary = state_path.with_suffix('.tmp')
        temporary.write_text(json.dumps(state, indent=2) + '\n')
        temporary.replace(state_path)

    def log(message):
        line = datetime.datetime.now().astimezone().isoformat(timespec='seconds') + ' ' + message
        print(line, flush=True)
        with (directory / 'events.log').open('a') as output:
            output.write(line + '\n')

    save()
    log('Runner started; first push attempt in 15 minutes')
    while state['index'] < len(changes):
        # Every attempt is separated by at least 15 minutes, including retries.
        time.sleep(900)
        change = changes[state['index']]
        if state['pending'] is None:
            with tempfile.TemporaryDirectory(prefix='scheduled-push-') as temporary:
                work = Path(temporary) / 'work'
                try:
                    run(['git', 'worktree', 'add', '--detach', str(work), state['base']], root)
                    run(['git', 'apply', '--index', change['patch']], work)
                    for check in change['checks']:
                        run(check, work)
                    # Commit only patch contents, never files generated by checks.
                    run(['git', 'diff', '--exit-code'], work)
                    run(['git', 'commit', '-m', change['message']], work)
                    state['pending'] = run(['git', 'rev-parse', 'HEAD'], work)
                    run(['git', 'update-ref', 'refs/scheduled-push/pending', state['pending']], root)
                    save()
                except (subprocess.SubprocessError, OSError) as error:
                    log('Change skipped: ' + str(error) + ' ' + str(getattr(error, 'stdout', '') or ''))
                    state['failed'] += 1
                    state['index'] += 1
                    save()
                    continue
                finally:
                    if work.exists():
                        run(['git', 'worktree', 'remove', '--force', str(work)], root)
        try:
            run(['git', 'push', args.remote,
                 state['pending'] + ':refs/heads/' + args.branch], root)
        except (subprocess.SubprocessError, OSError) as error:
            log('Push failed; retry next interval: ' + str(error) + ' ' + str(getattr(error, 'stdout', '') or ''))
            continue
        state['base'] = state['pending']
        state['pending'] = None
        state['index'] += 1
        state['pushes'] += 1
        save()
        log(f"Pushed {state['pushes']}: {change['message']}")
    log(f"Complete: {state['pushes']} pushes; {state['failed']} skipped changes")


if __name__ == '__main__':
    main()
